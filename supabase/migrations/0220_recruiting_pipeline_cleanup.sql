-- Hand entry and job-board posting titles left person_recruiting with many
-- near-duplicate values ("Veterinary Receptionist" / "Receptionist" /
-- "In-House CSR", "Pass" / "No hire" / "Not moving forward", zip-code
-- variants of the same clinic…). Collapse every column the ATS filters on onto
-- the canonical vocabulary in src/lib/ats/normalize.ts, which every write path
-- now also applies so the duplicates don't come back.
--
--   Position   81 -> 24 distinct      Source      26 -> 15
--   Stage      34 -> 17               Applied to   7 -> 5 (clinic names)
--   Pipeline   11 -> 9
--
-- The value lists below were generated by running the normalizer over the
-- live distinct values. Ambiguous legacy shorthand (DA, DH, Legal, "Entry
-- Level Opportunities") is left as-is. The original values are kept in
-- person_recruiting_cleanup_0220 so the cleanup can be audited or reverted.
-- updated_at is left untouched: this is not a recruiter edit.
-- ============================================================================

