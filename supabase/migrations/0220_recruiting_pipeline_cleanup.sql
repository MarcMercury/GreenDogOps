where job_location is null and target_title in ('CSR - SO', 'Vet Tech - SO');

update person_recruiting set job_location = 'Venice'
where job_location is null
  and target_title in ('CSR - Venice', 'Fac - Venice', 'Summer INTERN (CSR) Venice');

-- ---------------------------------------------------------------------------
-- 2. "DO NOT CONTACT AGAIN" becomes Passed; keep the warning in status notes.
-- ---------------------------------------------------------------------------
update person_recruiting
set status_notes = concat_ws(e'\n', nullif(status_notes, ''), 'DO NOT CONTACT AGAIN')
where stage = 'DO NOT CONTACT AGAIN';

