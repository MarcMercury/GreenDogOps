-- ---------------------------------------------------------------------------
create table if not exists person_recruiting_cleanup_0220 as
select person_id, target_title, stage, source, source_detail, job_location,
       pipeline, status_notes, now() as backed_up_at
from person_recruiting;

alter table person_recruiting_cleanup_0220 enable row level security;
